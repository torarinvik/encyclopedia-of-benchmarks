"""Independent bounded oracle for RSynth's natural glottal-source recurrence."""
from __future__ import annotations

import math
import struct
from collections.abc import Sequence

MIN_OPEN = 40
MAX_OPEN = 263
MAX_SAMPLE_INDEX = 299
MAX_INPUT_LENGTH = 2
MAX_PARSEABLE_INPUT_LENGTH = 3
MAX_OUTPUT_ELEMENTS = 1

def _f32(value: float) -> float:
    return struct.unpack(">f", struct.pack(">f", value))[0]

def _integral(value: float) -> bool:
    return value.is_integer()

def expected_output(values: Sequence[float] | None,
                    output_capacity: int | None = MAX_OUTPUT_ELEMENTS,
                    output_is_null: bool = False,
                    input_is_null: bool = False,
                    input_length: int | None = None) -> tuple[int, tuple[float, ...]]:
    if (type(input_is_null) is not bool or input_is_null or values is None
            or not isinstance(values, (list, tuple))
            or not 1 <= len(values) <= MAX_PARSEABLE_INPUT_LENGTH
            or (input_length is not None and
                (type(input_length) is not int or input_length != len(values)))
            or any(type(v) not in (int, float) or not math.isfinite(float(v)) for v in values)):
        return -1, ()
    if len(values) != MAX_INPUT_LENGTH:
        return -1, ()
    if any(not _integral(float(v)) for v in values):
        return -1, ()
    nopen, sample_index = (int(v) for v in values)
    if not MIN_OPEN <= nopen <= MAX_OPEN or not 0 <= sample_index <= MAX_SAMPLE_INDEX:
        return -1, ()

    # The pinned 224-entry table is generated by truncating 1,920,000/nopen^2.
    natglot_b = _f32(float(1_920_000 // (nopen * nopen)))
    natglot_a = _f32(_f32(natglot_b * float(nopen)) * 0.333)
    vwave = _f32(0.0)
    result = _f32(0.0)
    if sample_index < nopen:
        for _ in range(sample_index + 1):
            natglot_a = _f32(natglot_a - natglot_b)
            vwave = _f32(vwave + natglot_a)
        result = _f32(float(vwave) * 0.028)

    if type(output_is_null) is not bool or type(output_capacity) is not int or output_capacity < 0:
        return -1, ()
    if output_is_null or output_capacity < 1:
        return -2, ()
    return 1, (float(result),)

oracle = expected_output
